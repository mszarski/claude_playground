"""Fitting w2, gamma2, sigma2 to backscattering strength (sim/sediment_fit.py, tools/fit_sediment.py):
curves generated by our own model with noise are fitted back, the reported uncertainties cover
the errors, and data that cannot fix a parameter are flagged."""

import dataclasses
import subprocess
import sys
import warnings
from pathlib import Path

import numpy as np
import pytest
import yaml

from gpusonar.sim import bottom, sediment_fit

C = 1500.0
ROOT = Path(__file__).resolve().parents[2]


def synthetic(params, angles_deg, freqs, noise_db, seed):
    g, f = np.meshgrid(np.asarray(angles_deg, dtype=float), np.asarray(freqs, dtype=float))
    g, f = g.ravel(), f.ravel()
    # Made with the model the fit uses unless told otherwise (first-order perturbation theory; the
    # forward default is small_slope since D-86), so that a noise-free fit can be exact.
    truth = np.concatenate([bottom.backscattering_strength_db(np.radians(g[f == v]), v, C, roughness_model="perturbation", **params)
                            for v in np.unique(f)])
    order = np.concatenate([np.flatnonzero(f == v) for v in np.unique(f)])
    y = np.empty(len(g))
    y[order] = truth
    return g, f, y + np.random.default_rng(seed).normal(0.0, noise_db, len(g))


def geo(params):
    return {k: params[k] for k in ("rho", "nu", "delta")}


def test_recovers_sand_from_two_frequencies_within_the_reported_uncertainty():
    """Medium sand, 5 to 55 degrees, 20 and 200 kHz, 0.5 dB noise: roughness dominates at the
    high frequency and the volume term shows at the low one, so all three are identifiable."""
    truth = bottom.sediment("medium_sand")
    inside, total = 0, 0
    for seed in range(4):
        g, f, y = synthetic(truth, np.arange(5.0, 56.0, 2.5), [20e3, 200e3], 0.5, seed)
        fit = sediment_fit.fit(g, f, y, sound_speed=C, sigma_db=0.5, **geo(truth))
        assert fit.unconstrained == [], fit.notes
        assert fit.fitted == ("w2", "gamma2", "sigma2") and fit.n_points == len(y)
        assert 0.3 < fit.rms_residual_db < 0.8                       # the noise, not a misfit
        for k in fit.fitted:
            err = np.log10(fit.params[k] / truth[k]) if k in sediment_fit.LOG_KEYS else fit.params[k] - truth[k]
            assert abs(err) < 4.0 * fit.std[k], (k, err, fit.std[k])
            inside += abs(err) < 2.0 * fit.std[k]
            total += 1
        assert fit.factor("w2") < 1.6 and fit.factor("sigma2") < 1.6 and fit.std["gamma2"] < 0.1
        assert fit.params["rho"] == truth["rho"]                     # held
    assert inside >= 0.75 * total                                    # 2 sigma should hold about 95 % of the time


def test_noise_free_fit_is_exact_and_uses_the_residual_for_the_error():
    truth = bottom.sediment("medium_sand")
    g, f, y = synthetic(truth, np.arange(5.0, 56.0, 5.0), [30e3, 100e3], 0.0, 0)
    fit = sediment_fit.fit(g, f, y, sound_speed=C, **geo(truth))
    for k in ("w2", "gamma2", "sigma2"):
        assert fit.params[k] == pytest.approx(truth[k], rel=1e-4)
    assert fit.rms_residual_db < 1e-4 and np.allclose(fit.model_db(g, f), y, atol=1e-3)


def test_the_row_writes_numbers_plain_yaml_reads_as_numbers():
    """`:g` writes 0.00001 as `1e-05`, which PyYAML (YAML 1.1) reads as a string; the row writes `1.0e-05`, and the
    sediment table (read with plain yaml.safe_load) gets a number back (sonar-iwq)."""
    assert [sediment_fit.yaml_number(v, ".6g") for v in (1e-5, 2.5e-7, 1.41e-4, 3.25, 2e6, 0.5)] == \
        ["1.0e-05", "2.5e-07", "0.000141", "3.25", "2.0e+06", "0.5"]
    for v in (1e-5, 3e-6, 2e6, 1.5e-9):
        assert yaml.safe_load(f"v: {sediment_fit.yaml_number(v, '.3g')}")["v"] == pytest.approx(v)
    truth = bottom.sediment("medium_sand")
    g, f, y = synthetic(truth, np.arange(5.0, 56.0, 5.0), [30e3, 100e3], 0.0, 0)
    fit = sediment_fit.fit(g, f, y, sound_speed=C, **geo(truth))
    fit = dataclasses.replace(fit, params=dict(fit.params, w2=1e-5, sigma2=2e-6), rms_residual_db=3e-6,
                              std=dict(fit.std, gamma2=1e-5))
    row = yaml.safe_load(fit.yaml_row("site", "synthetic sand"))["site"]
    assert (row["w2"], row["sigma2"], row["fit"]["rms_residual_db"], row["fit"]["one_sigma"]["gamma2"]) == (1e-5, 2e-6, 3e-6, 1e-5)


def test_volume_dominated_data_do_not_fix_the_roughness():
    """Very fine silt at one frequency: volume scattering is more than 100 times the roughness
    term, so sigma2 is found and w2, gamma2 are reported as unconstrained."""
    truth = bottom.sediment("very_fine_silt")
    g, f, y = synthetic(truth, np.arange(8.0, 46.0, 2.0), [100e3], 0.5, 1)
    fit = sediment_fit.fit(g, f, y, sound_speed=C, sigma_db=0.5, **geo(truth))
    assert "w2" in fit.unconstrained and "gamma2" in fit.unconstrained and "sigma2" not in fit.unconstrained
    assert fit.roughness_share[1] < 0.5
    assert any("mostly volume scattering and do not fix w2 or gamma2" in n for n in fit.notes)
    assert fit.params["sigma2"] == pytest.approx(truth["sigma2"], rel=0.25)
    row = yaml.safe_load(fit.yaml_row("site", "synthetic silt"))["site"]
    assert set(row["unconfirmed_fields"]) >= {"w2", "gamma2"} and row["status"] == "fitted (synthetic silt)"


def test_one_frequency_at_low_angles_cannot_separate_strength_from_exponent():
    """Sand at 300 kHz, 5 to 25 degrees: roughness only, and at one frequency the level fixes
    w2 (2k)^-gamma2, not each. Both are flagged, with the reason; so is sigma2 (not seen)."""
    truth = bottom.sediment("medium_sand")
    g, f, y = synthetic(truth, np.arange(5.0, 26.0, 1.0), [300e3], 0.5, 2)
    fit = sediment_fit.fit(g, f, y, sound_speed=C, sigma_db=0.5, **geo(truth))
    assert {"w2", "gamma2", "sigma2"} <= set(fit.unconstrained)
    assert any("one frequency" in n for n in fit.notes) and any("upper limit on sigma2" in n for n in fit.notes)
    assert fit.rms_residual_db < 1.0                                 # the curve itself is still fitted
    # The combination the data do fix is right: the roughness level at the data's frequency.
    k = 2 * np.pi * 300e3 / C
    level = lambda p: p["w2"] * (2 * k * np.cos(np.radians(15.0))) ** -p["gamma2"]          # noqa: E731
    assert level(fit.params) == pytest.approx(level(truth), rel=0.15)


def test_a_fitted_row_loads_and_warns_only_about_what_the_data_left_open(tmp_path):
    truth = bottom.sediment("medium_sand")
    g, f, y = synthetic(truth, np.arange(5.0, 56.0, 2.5), [20e3, 200e3], 0.3, 3)
    fit = sediment_fit.fit(g, f, y, sound_speed=C, sigma_db=0.3, **geo(truth))
    table = tmp_path / "s.yaml"
    table.write_text(fit.yaml_row("good", "synthetic, two frequencies"))
    with warnings.catch_warnings():
        warnings.simplefilter("error")                               # a fitted row with nothing left open is quiet
        got = bottom.sediment("good", table)
    assert got == pytest.approx(fit.params, rel=1e-5)
    g, f, y = synthetic(bottom.sediment("very_fine_silt"), np.arange(8.0, 46.0, 2.0), [100e3], 0.5, 1)
    poor = sediment_fit.fit(g, f, y, sound_speed=C, sigma_db=0.5, **geo(bottom.sediment("very_fine_silt")))
    table.write_text(poor.yaml_row("poor", "synthetic silt"))
    with pytest.warns(UserWarning, match=r"poor.*w2"):
        bottom.sediment("poor", table)


def test_input_checks_and_model_validity_note():
    truth = bottom.sediment("medium_sand")
    with pytest.raises(ValueError, match="cannot determine"):
        sediment_fit.fit([10.0, 20.0], 100e3, [-30.0, -28.0], **geo(truth))
    with pytest.raises(ValueError, match="grazing"):
        sediment_fit.fit([0.0, 20.0, 30.0], 100e3, [-30.0, -28.0, -27.0], **geo(truth))
    g, f, y = synthetic(truth, np.arange(10.0, 81.0, 5.0), [100e3], 0.2, 0)
    fit = sediment_fit.fit(g, f, y, sound_speed=C, sigma_db=0.2, n_starts=4, **geo(truth))
    assert any("not valid there" in n for n in fit.notes)


def test_tool_end_to_end(tmp_path):
    """The command-line tool on a CSV, holding rho, nu, delta from a reflection-only row."""
    held = bottom.sediment_reflection("fine_sand")
    truth = dict(held, w2=3.0e-5, gamma2=3.1, sigma2=2.0e-3)
    g, f, y = synthetic(truth, np.arange(5.0, 56.0, 2.5), [30e3, 300e3], 0.4, 5)
    data = tmp_path / "bs.csv"
    data.write_text("# synthetic\ngrazing_deg,frequency_hz,bs_db,sigma_db\n" + "".join(f"{a},{b},{c},0.4\n" for a, b, c in zip(g, f, y)))
    out = tmp_path / "row.yaml"
    run = subprocess.run([sys.executable, str(ROOT / "tools" / "fit_sediment.py"), "--data", str(data), "--sediment", "fine_sand",
                          "--name", "my_site", "--source", "synthetic test data", "--out", str(out), "--starts", "6"],
                         capture_output=True, text=True, env={"PYTHONPATH": str(ROOT / "python"), "PATH": "/usr/bin:/bin"})
    assert run.returncode == 0, run.stderr
    row = yaml.safe_load(out.read_text())["my_site"]
    assert row["status"] == "fitted (synthetic test data)" and "unconfirmed_fields" not in row
    assert row["rho"] == pytest.approx(held["rho"], rel=1e-5)
    assert row["w2"] == pytest.approx(truth["w2"], rel=0.5) and row["gamma2"] == pytest.approx(truth["gamma2"], abs=0.15)
    assert row["sigma2"] == pytest.approx(truth["sigma2"], rel=0.5)
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        assert bottom.sediment("my_site", out)["w2"] == row["w2"]
