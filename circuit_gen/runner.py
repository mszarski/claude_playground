"""
Run SKiDL circuit code in a subprocess and collect the resulting circuit.

The circuit code (hand-written or generated by the model) is wrapped with a
prelude that points SKiDL at the KiCad libraries and an epilogue that runs
SKiDL's electrical rules check (ERC) and dumps the circuit to JSON. Running in
a subprocess keeps SKiDL's global circuit state isolated between attempts.
Note that a subprocess is not a security sandbox: only run generated code you
are willing to execute on this machine.
"""

import json
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from . import config

PRELUDE = '''\
import os, sys, json, logging
os.environ.setdefault("KICAD7_SYMBOL_DIR", {symbol_dir!r})
from skidl import *
set_default_tool(KICAD7)
lib_search_paths[KICAD7].append({symbol_dir!r})
footprint_search_paths[KICAD7].append({footprint_dir!r})

_REQUIREMENTS = []
def require(measure, low, high, sources=None, loads=None, analysis="op", freq=1000, name=None):
    """Declare a behaviour the circuit must have; checked in ngspice across tolerances."""
    if not isinstance(measure, str):
        raise TypeError("require(): measure must be a string such as 'v(OUT)'")
    low, high = float(low), float(high)
    if low > high:
        raise ValueError(f"require({{measure!r}}): low {{low}} is above high {{high}}")
    if analysis not in ("op", "ac"):
        raise ValueError("require(): analysis must be 'op' or 'ac'")
    _REQUIREMENTS.append({{"measure": measure, "min": low, "max": high,
                          "sources": dict(sources or {{}}), "loads": dict(loads or {{}}),
                          "analysis": analysis, "freq": float(freq), "name": name}})
# ---- circuit code starts here ----
'''

EPILOGUE = '''
# ---- circuit code ends here ----
def _dump_circuit(path):
    parts = []
    for p in default_circuit.parts:
        pins = []
        for pin in p.pins:
            pins.append({
                "num": str(pin.num),
                "name": str(pin.name),
                "type": getattr(pin.func, "name", str(pin.func)),
                "net": pin.net.name if pin.is_connected() and pin.net else None,
            })
        parts.append({
            "ref": p.ref,
            "symbol": f"{getattr(p.lib, 'filename', p.lib)}:{p.name}",
            "value": str(p.value),
            "footprint": p.footprint or "",
            "tolerance": getattr(p, "tolerance", None),
            "pins": pins,
        })
    with open(path, "w") as f:
        json.dump({"parts": parts, "requirements": _REQUIREMENTS}, f, indent=1)

print("@@ERC_START@@", flush=True)
ERC()
print("@@ERC_END@@", flush=True)
_dump_circuit("circuit.json")
generate_netlist(file_="circuit.net")
'''

_ERC_LINE = re.compile(r"ERC (ERROR|WARNING): (.*)")
_TRACEBACK_TAIL_LINES = 15


@dataclass
class RunResult:
    ok: bool
    circuit: dict | None = None
    erc_errors: list = field(default_factory=list)
    erc_warnings: list = field(default_factory=list)
    error: str | None = None
    netlist_path: Path | None = None

    def summary(self):
        """Short text report suitable for feeding back to the model."""
        if not self.ok:
            return f"Circuit code failed to run:\n{self.error}"
        lines = [f"Circuit ran: {len(self.circuit['parts'])} parts."]
        lines += [f"ERC ERROR: {e}" for e in self.erc_errors]
        lines += [f"ERC WARNING: {w}" for w in self.erc_warnings]
        return "\n".join(lines)


def wrap_code(code):
    """Return the full script that runs `code` with the prelude and epilogue."""
    prelude = PRELUDE.format(
        symbol_dir=str(config.KICAD_SYMBOL_DIR),
        footprint_dir=str(config.KICAD_FOOTPRINT_DIR),
    )
    return prelude + code + "\n" + EPILOGUE


def _clean_output(text):
    # SKiDL warns about every library path it could not find; drop that noise.
    keep = []
    for line in text.splitlines():
        if "symbol libraries won't be searched" in line or "fp-lib-table file was not found" in line:
            continue
        keep.append(line)
    return "\n".join(keep)


def run_circuit_code(code, workdir, timeout=120):
    """Run SKiDL `code` inside `workdir` and return a RunResult."""
    workdir = Path(workdir)
    workdir.mkdir(parents=True, exist_ok=True)
    script = workdir / "circuit_run.py"
    script.write_text(wrap_code(code))
    (workdir / "circuit.json").unlink(missing_ok=True)

    try:
        proc = subprocess.run(
            [config.PYTHON, script.name],
            cwd=workdir,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        return RunResult(ok=False, error=f"timed out after {timeout}s")

    output = _clean_output(proc.stdout + "\n" + proc.stderr)
    if proc.returncode != 0 or not (workdir / "circuit.json").exists():
        tail = "\n".join(output.strip().splitlines()[-_TRACEBACK_TAIL_LINES:])
        return RunResult(ok=False, error=tail or f"exit code {proc.returncode}")

    erc_errors, erc_warnings = [], []
    for m in _ERC_LINE.finditer(output):
        kind, msg = m.group(1), m.group(2).strip()
        # Strip SKiDL's "@ [file:line]" location suffix; it points into the wrapper.
        msg = re.sub(r"\s*@ \[.*\]$", "", msg)
        (erc_errors if kind == "ERROR" else erc_warnings).append(msg)

    circuit = json.loads((workdir / "circuit.json").read_text())
    return RunResult(
        ok=True,
        circuit=circuit,
        erc_errors=erc_errors,
        erc_warnings=erc_warnings,
        netlist_path=workdir / "circuit.net",
    )
